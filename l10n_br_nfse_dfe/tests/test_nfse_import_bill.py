import base64
from datetime import timedelta

from odoo import Command
from odoo.tests.common import TransactionCase, tagged

from .test_nfse_dfe import nfse_xml


@tagged("post_install", "-at_install")
class TestNfseImportBill(TransactionCase):
    def test_bill_of_an_imported_nfse_discounts_the_withheld_issqn(self):
        company = self.env.ref("l10n_br_base.empresa_lucro_presumido")
        env = self.env(
            context=dict(
                self.env.context,
                tracking_disable=True,
                allowed_company_ids=[company.id],
            )
        )
        wizard = env["l10n_br_fiscal.document.import.wizard"].create(
            {
                "company_id": company.id,
                "file": base64.b64encode(nfse_xml(retention="2")),
            }
        )
        if not hasattr(wizard, "action_import_and_open_move"):
            # the bill is generated by l10n_br_account, which l10n_br_nfse_dfe
            # does not depend on: skip it when the module is not installed
            self.skipTest("l10n_br_account is not installed")
        company.nfse_import_product_id = env["product.product"].create(
            {"name": "Imported NFS-e service", "type": "service"}
        )
        wizard._onchange_file()
        action = wizard.action_import_and_open_move()
        move = env["account.move"].browse(action["res_id"])
        self.assertTrue(move.imported_document)

        move.invoice_payment_term_id = env["account.payment.term"].create(
            {
                "name": "Two installments",
                "line_ids": [
                    Command.create(
                        {"value": "percent", "value_amount": 50.0, "days": 30}
                    ),
                    Command.create(
                        {"value": "balance", "value_amount": 0.0, "days": 60}
                    ),
                ],
            }
        )
        withheld = move.line_ids.filtered(
            lambda line: line.display_type == "tax"
            and line.tax_line_id.tax_group_id.fiscal_tax_group_id.tax_withholding
        )
        self.assertEqual(len(withheld), 1)
        self.assertAlmostEqual(withheld.balance, -0.40, places=2)
        due_lines = move.line_ids.filtered(
            lambda line: line.display_type == "payment_term"
        ).sorted("date_maturity")
        self.assertEqual(
            due_lines.mapped("date_maturity"),
            [
                move.invoice_date + timedelta(days=30),
                move.invoice_date + timedelta(days=60),
            ],
        )
        self.assertAlmostEqual(sum(due_lines.mapped("credit")), 19.60, places=2)
        self.assertAlmostEqual(sum(move.line_ids.mapped("balance")), 0.0, places=2)
